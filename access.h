#ifndef ACCESS_H
#define ACCESS_H

// Модуль имитации системы контроля доступа:
// ввод 4-значного кода с клавиатуры, отображение на TM1637,
// сигнализация результата зелёным/красным светодиодом.

// Настраивает светодиоды результата (PA9 - разрешено, PA15 - отказано)
// и очищает индикатор. Вызывается один раз при старте, после tm1637_init().
void initAccess(void);

// Вызывается на каждой итерации главного цикла с результатом
// scanKeyboard(): новой нажатой клавишей или '\0', если ничего не нажато.
// Вся логика ввода/проверки/индикации находится внутри.
void updateAccess(char key);

#endif
